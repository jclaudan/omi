def update_arb(path, locale):
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    changed = False
    for key, translations in NEW_KEYS.items():
        if key in data:
            continue
        value = translations.get(locale, translations['en'])
        data[key] = value
        if locale == 'en' and key in DESCRIPTIONS:
            data[f'@{key}'] = {'description': DESCRIPTIONS[key]}
        changed = True

    if changed:
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=4)
            f.write('\n')
        print(f'  Updated {os.path.basename(path)}')

def main():
    arb_files = sorted(f for f in os.listdir(L10N_DIR) if f.startswith('app_') and f.endswith('.arb'))
    for filename in arb_files:
        locale = filename[4:-4]
        path = os.path.join(L10N_DIR, filename)
        update_arb(path, locale)
    print('Done.')

if __name__ == '__main__':
    main()
